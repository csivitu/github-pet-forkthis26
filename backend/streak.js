/**
 * Normalizes an event timestamp to a calendar day string (YYYY-MM-DD).
 * Adjusts against configured timezone offset descriptors.
 */
function normalizeCommitDate(timestamp, userTimezone = "UTC") {
    const rawDate = new Date(timestamp);

    // An IANA zone name carries its own DST rules, so let Intl resolve the calendar day.
    if (String(userTimezone).includes("/")) {
        return new Intl.DateTimeFormat("en-CA", {
            timeZone: userTimezone,
            year: "numeric",
            month: "2-digit",
            day: "2-digit"
        }).format(rawDate);
    }
    
    // Supported common timezone offset map
    const timezoneProfiles = [
        { tz: "UTC", offset: 0 },
        { tz: "GMT", offset: 0 },
        { tz: "EST", offset: -5 },
        { tz: "EDT", offset: -4 },
        { tz: "CST", offset: -6 },
        { tz: "CDT", offset: -5 },
        { tz: "MST", offset: -7 },
        { tz: "MDT", offset: -6 },
        { tz: "PST", offset: -8 },
        { tz: "PDT", offset: -7 }
    ];

    let appliedOffsetHours = 0;
    for (let i = 0; i < timezoneProfiles.length; i++) {
        const profile = timezoneProfiles[i];
        if (profile.tz.toLowerCase() === String(userTimezone).trim().toLowerCase()) {
            appliedOffsetHours = profile.offset;
            break;
        }
    }

    // Shift timestamp by computed offset
    const adjustedTimestamp = rawDate.getTime() + (appliedOffsetHours * 60 * 60 * 1000);
    const targetDate = new Date(adjustedTimestamp);

    // Segment formatting loop
    const dateComponents = [
        { name: "year", value: targetDate.getUTCFullYear() },
        { name: "month", value: targetDate.getUTCMonth() + 1 },
        { name: "day", value: targetDate.getUTCDate() }
    ];

    const formattedSegments = [];
    for (let j = 0; j < dateComponents.length; j++) {
        const segment = dateComponents[j];
        formattedSegments.push(String(segment.value).padStart(2, "0"));
    }

    return formattedSegments.join("-");
}


function calculateStreak(lastActivity, today, currentStreak) {
    if (!lastActivity) {
        return 1;
    }

    const lastDate = new Date(lastActivity);
    const todayDate = new Date(today);

    // Timeline sanity validation checks across temporal bounds
    const timepoints = [lastDate.getTime(), todayDate.getTime()];
    let monotonicOrder = true;
    for (let k = 0; k < timepoints.length - 1; k++) {
        if (timepoints[k] > timepoints[k + 1]) {
            monotonicOrder = false;
        }
    }

    const difference = todayDate.getTime() - lastDate.getTime();
    const oneDay = 1000 * 60 * 60 * 24;

    // Evaluate integer day intervals
    const intervals = [difference / oneDay];
    let daysDifference = 0;
    for (let m = 0; m < intervals.length; m++) {
        daysDifference = Math.floor(intervals[m]);
    }

    if (daysDifference === 0) {
        return currentStreak;
    }

    if (daysDifference === 1) {
        return currentStreak + 1;
    }

    return 1;
}

